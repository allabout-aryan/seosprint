import React, { useEffect, useState } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { ArrowRight, AlertTriangle, Loader2, ExternalLink, ShieldCheck, Swords, Search } from 'lucide-react';
import { Logo, Card, CardHead, Badge, Empty, ConnectorGlyph } from '../components/ui';
import { Donut } from '../components/charts';
import { loadReport, shareUrl, type Report } from '../lib/reports';
import { ISSUE_META } from '../lib/live';
import { fmtNum } from '../lib/format';

const SEV_TONE: Record<string, string> = { critical: 'neg', high: 'warn', medium: 'info', low: '' };
const KIND_LABEL: Record<string, string> = { audit: 'Page audit', site: 'Site crawl', compare: 'Competitor compare', serp: 'SERP check' };

export default function ReportView() {
  const { id } = useParams<{ id: string }>();
  const nav = useNavigate();
  const [report, setReport] = useState<Report | null>(null);
  const [state, setState] = useState<'loading' | 'ready' | 'missing'>('loading');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    let alive = true;
    (async () => {
      if (!id) { setState('missing'); return; }
      const r = await loadReport(id);
      if (!alive) return;
      if (r) { setReport(r); setState('ready'); } else setState('missing');
    })();
    return () => { alive = false; };
  }, [id]);

  const copy = () => {
    navigator.clipboard?.writeText(shareUrl(id || ''));
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  };

  return (
    <div style={{ minHeight: '100%', background: 'var(--bg)' }}>
      <div className="topbar" style={{ position: 'sticky', top: 0 }}>
        <button className="btn btn-ghost btn-sm" onClick={() => nav('/')} style={{ paddingLeft: 0 }}>
          <Logo size={24} />
        </button>
        <span className="badge accent" style={{ marginLeft: 6 }}>
          {report ? KIND_LABEL[report.kind] || report.kind : 'Shared report'}
        </span>
        <div className="row gap8" style={{ marginLeft: 'auto' }}>
          <button className="btn btn-sm" onClick={copy}>{copied ? 'Link copied' : 'Copy link'}</button>
          <button className="btn btn-primary btn-sm" onClick={() => nav('/app/crawl')}>
            Run your own <ArrowRight size={14} />
          </button>
        </div>
      </div>

      <div style={{ maxWidth: 980, margin: '0 auto', padding: '26px 20px 60px' }}>
        {state === 'loading' && (
          <Card><div className="card-pad row gap10"><Loader2 size={16} style={{ animation: 'spin 1s linear infinite' }} /><span className="sm muted">Loading report…</span></div></Card>
        )}

        {state === 'missing' && (
          <Card>
            <Empty
              title="This report doesn't exist"
              sub="The link may be mistyped, or the report was removed. Reports are kept for 90 days."
              action={<button className="btn btn-primary btn-sm" onClick={() => nav('/app/crawl')}>Run a fresh crawl</button>}
            />
          </Card>
        )}

        {state === 'ready' && report && <Body report={report} />}

        <div className="row gap8 wrap" style={{ justifyContent: 'center', marginTop: 30 }}>
          <span className="tiny muted">Generated by SeoSprint — a Google-free SEO crawler.</span>
          <button className="btn btn-sm" onClick={() => nav('/app/crawl')}>Crawl any site free <ArrowRight size={13} /></button>
        </div>
      </div>
    </div>
  );
}

function Body({ report }: { report: Report }) {
  const p = report.payload || {};
  if (report.kind === 'audit') return <AuditBody r={report} p={p} />;
  if (report.kind === 'site') return <SiteBody r={report} p={p} />;
  if (report.kind === 'compare') return <CompareBody r={report} p={p} />;
  if (report.kind === 'serp') return <SerpBody r={report} p={p} />;
  return null;
}

function Header({ title, sub, right }: { title: string; sub?: string; right?: React.ReactNode }) {
  return (
    <div className="between wrap gap12" style={{ marginBottom: 16 }}>
      <div>
        <h1 style={{ fontSize: 24, fontWeight: 760, letterSpacing: '-.02em' }}>{title}</h1>
        {sub && <div className="sm muted" style={{ marginTop: 3 }}>{sub}</div>}
      </div>
      {right}
    </div>
  );
}

function ScoreBlock({ score, counts, label }: { score: number; counts: { critical: number; high: number; medium: number; low: number }; label: string }) {
  const color = score >= 80 ? 'var(--pos)' : score >= 60 ? 'var(--warn)' : 'var(--neg)';
  return (
    <Card style={{ marginBottom: 14 }}>
      <div className="card-pad row gap20 wrap">
        <Donut size={140} thickness={15} center={
          <div>
            <div className="num" style={{ fontSize: 30, fontWeight: 780, color }}>{score}</div>
            <div className="tiny muted">{label}</div>
          </div>
        } rows={[
          { label: 'Critical', value: counts.critical, color: '#fb7185' },
          { label: 'High', value: counts.high, color: '#fbbf24' },
          { label: 'Medium', value: counts.medium, color: '#60a5fa' },
          { label: 'Low', value: counts.low, color: '#7f8aa3' },
        ]} />
        <div className="col gap10 grow" style={{ minWidth: 200 }}>
          {(['critical', 'high', 'medium', 'low'] as const).map((s) => (
            <div key={s} className="between">
              <span className="row gap8">
                <i className="dot" style={{ background: s === 'critical' ? '#fb7185' : s === 'high' ? '#fbbf24' : s === 'medium' ? '#60a5fa' : '#7f8aa3' }} />
                <span className="sm" style={{ textTransform: 'capitalize' }}>{s}</span>
              </span>
              <span className="num sm strong">{counts[s]}</span>
            </div>
          ))}
        </div>
      </div>
    </Card>
  );
}

function AuditBody({ r, p }: { r: Report; p: any }) {
  const counts = p.counts || { critical: 0, high: 0, medium: 0, low: 0 };
  return (
    <>
      <Header
        title={p.page?.title || r.title || r.url || 'Page audit'}
        sub={p.finalUrl || r.url || ''}
        right={<Badge tone={r.score && r.score >= 80 ? 'pos' : r.score && r.score >= 60 ? 'warn' : 'neg'}>{r.score}/100</Badge>}
      />
      <ScoreBlock score={r.score || 0} counts={counts} label="page score" />

      <div className="grid g4" style={{ marginBottom: 14 }}>
        {[
          ['Words', fmtNum(p.stats?.words ?? 0)],
          ['Response', `${p.stats?.responseMs ?? 0} ms`],
          ['HTML', `${p.stats?.htmlKb ?? 0} KB`],
          ['Internal links', String(p.stats?.internalLinks ?? 0)],
        ].map(([k, v]) => (
          <Card key={k} className="kpi">
            <div className="label">{k}</div>
            <div className="value num" style={{ fontSize: 20 }}>{v}</div>
          </Card>
        ))}
      </div>

      <Card>
        <CardHead title="Findings" sub={`${(p.findings || []).length} checks failed`} />
        <div>
          {(p.findings || []).map((f: any) => (
            <div key={f.id} style={{ padding: '12px 16px', borderBottom: '1px solid rgba(255,255,255,.045)' }}>
              <div className="between" style={{ marginBottom: 4 }}>
                <span className="sm strong">{f.title}</span>
                <Badge tone={SEV_TONE[f.severity]}>{f.severity}</Badge>
              </div>
              <div className="tiny muted" style={{ marginBottom: 4 }}>{f.detail}</div>
              <div className="tiny" style={{ color: 'var(--pos)' }}>Fix: {f.fix}</div>
            </div>
          ))}
          {(p.findings || []).length === 0 && <Empty title="No issues found" sub="This page passed every check." />}
        </div>
      </Card>
    </>
  );
}

function SiteBody({ r, p }: { r: Report; p: any }) {
  const counts = {
    critical: (p.home?.findings || []).filter((f: any) => f.severity === 'critical').length,
    high: (p.home?.findings || []).filter((f: any) => f.severity === 'high').length,
    medium: (p.home?.findings || []).filter((f: any) => f.severity === 'medium').length,
    low: (p.home?.findings || []).filter((f: any) => f.severity === 'low').length,
  };
  return (
    <>
      <Header title={p.origin || r.url || 'Site crawl'} sub={`${p.crawled} pages crawled · ${p.sitemapUrls} URLs in sitemap`}
        right={<Badge tone={(r.score || 0) >= 80 ? 'pos' : (r.score || 0) >= 60 ? 'warn' : 'neg'}>{r.score}/100</Badge>} />
      <ScoreBlock score={r.score || 0} counts={counts} label="site score" />

      <Card style={{ marginBottom: 14 }}>
        <CardHead title="Pages" sub={`${(p.pages || []).length} crawled`} />
        <div className="tbl-scroll" style={{ maxHeight: '50vh' }}>
          <table className="tbl">
            <thead><tr><th>URL</th><th className="r">Score</th><th className="r">Words</th><th className="r">Issues</th></tr></thead>
            <tbody>
              {(p.pages || []).map((pg: any) => (
                <tr key={pg.url}>
                  <td><div className="sm truncate" style={{ maxWidth: 380 }}>{pg.title || pg.url}</div><div className="tiny muted mono truncate" style={{ maxWidth: 380 }}>{pg.url}</div></td>
                  <td className="r"><Badge tone={pg.score >= 80 ? 'pos' : pg.score >= 60 ? 'warn' : 'neg'}>{pg.score}</Badge></td>
                  <td className="r num muted">{fmtNum(pg.words)}</td>
                  <td className="r num muted">{pg.issueCount}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>

      <Card>
        <CardHead title="Issues by frequency" sub="How many crawled pages each check failed on" />
        <div>
          {(p.issues || []).map((iss: any) => {
            const m = ISSUE_META[iss.id] || { title: iss.id, severity: 'medium', category: 'Other', fix: '' };
            return (
              <div key={iss.id} className="between" style={{ padding: '11px 16px', borderBottom: '1px solid rgba(255,255,255,.045)' }}>
                <span className="row gap10">
                  <Badge tone={SEV_TONE[m.severity]}>{m.severity}</Badge>
                  <span>
                    <div className="sm strong">{m.title}</div>
                    <div className="tiny muted">{m.category} · {m.fix}</div>
                  </span>
                </span>
                <span className="num sm">{iss.count} page{iss.count === 1 ? '' : 's'}</span>
              </div>
            );
          })}
        </div>
      </Card>
    </>
  );
}

function CompareBody({ r, p }: { r: Report; p: any }) {
  const rows = (p.rows || []).filter((x: any) => x.ok);
  const metrics = [
    ['Health score', 'score'], ['Words', 'words'], ['H2 sections', 'h2Count'],
    ['Internal links', 'internalLinks'], ['External links', 'externalLinks'], ['Issues', 'findings'],
  ] as const;
  return (
    <>
      <Header title="Competitor compare" sub={rows.map((x: any) => x.domain).join(' vs ')} />
      <Card style={{ marginBottom: 14 }}>
        <CardHead title="Side by side" sub="Every page fetched and parsed by the same crawler" />
        <div className="tbl-scroll">
          <table className="tbl">
            <thead><tr><th>Metric</th>{rows.map((x: any, i: number) => <th key={i} className="r">{x.domain}</th>)}</tr></thead>
            <tbody>
              {metrics.map(([label, key]) => (
                <tr key={key}>
                  <td className="sm">{label}</td>
                  {rows.map((x: any, i: number) => <td key={i} className="r num muted">{String(x[key] ?? '—')}</td>)}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>
      <Card>
        <CardHead title="Topics they cover that you don't" sub="H2 headings missing from the first page" />
        <div className="card-pad col gap8">
          {(p.gaps || []).map((g: any) => (
            <div key={g.topic} className="between" style={{ background: 'rgba(255,255,255,.03)', borderRadius: 9, padding: '9px 12px' }}>
              <span className="sm truncate" style={{ textTransform: 'capitalize', maxWidth: 560 }}>{g.topic}</span>
              <Badge tone="warn">{g.rivals} competitor{g.rivals === 1 ? '' : 's'}</Badge>
            </div>
          ))}
          {(p.gaps || []).length === 0 && <Empty title="No heading gaps" sub="You cover every H2 your competitors use." />}
        </div>
      </Card>
    </>
  );
}

function SerpBody({ r, p }: { r: Report; p: any }) {
  return (
    <>
      <Header title={`“${p.query}”`} sub={`${(p.results || []).length} organic results · ${p.provider || 'search'}`}
        right={<Badge tone={p.yourRank ? 'pos' : 'warn'}>{p.yourRank ? `Your position #${p.yourRank}` : 'Not in top 20'}</Badge>} />
      <Card>
        <div className="tbl-scroll" style={{ maxHeight: '64vh' }}>
          <table className="tbl">
            <thead><tr><th className="r">#</th><th>Result</th><th className="r">Domain</th></tr></thead>
            <tbody>
              {(p.results || []).map((x: any) => (
                <tr key={x.position}>
                  <td className="r num muted">{x.position}</td>
                  <td>
                    <a href={x.url} target="_blank" rel="noreferrer" className="sm strong">{x.title}</a>
                    <div className="tiny muted truncate" style={{ maxWidth: 560 }}>{x.snippet || x.url}</div>
                  </td>
                  <td className="r tiny muted">{x.domain}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>
    </>
  );
}
